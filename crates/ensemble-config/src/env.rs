//! Reading the environment, and the variables Ensemble names for keys it keeps.

use super::*;

/// How the environment is read. Injected so validation is testable without
/// `set_var`, which is `unsafe` in edition 2024 and racy across threads.
pub trait Env {
    fn get(&self, key: &str) -> Option<String>;
}

pub struct SystemEnv;

impl Env for SystemEnv {
    fn get(&self, key: &str) -> Option<String> {
        std::env::var(key).ok()
    }
}

impl Env for BTreeMap<String, String> {
    fn get(&self, key: &str) -> Option<String> {
        BTreeMap::get(self, key).cloned()
    }
}

/// The variable that holds the API key of the provider `name` when Ensemble
/// keeps the key itself, sealed in its database:
/// `ENSEMBLE_PROVIDER_<NAME>_KEY`, its letters upper case and anything else `_`.
pub fn provider_key_variable(name: &str) -> String {
    let name: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    format!("ENSEMBLE_PROVIDER_{name}_KEY")
}
